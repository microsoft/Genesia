const replacements = Object.entries(english).sort(([left], [right]) => right.length - left.length)

export function translate(value: string, locale: Locale) {
  if (locale === 'zh' || !/[\u3400-\u9fff]/u.test(value)) return value

  const leading = value.match(/^\s*/u)?.[0] ?? ''
  const trailing = value.match(/\s*$/u)?.[0] ?? ''
  const content = value.slice(leading.length, value.length - trailing.length || undefined)
  const exact = english[content]

  if (exact) return `${leading}${exact}${trailing}`

  let translated = content
  for (const [source, target] of replacements) {
    if (translated.includes(source)) translated = translated.replaceAll(source, target)
  }

  return `${leading}${translated}${trailing}`
}
